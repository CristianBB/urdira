#!/usr/bin/env node
// Generates the v4 workspace-catalog SQL mirrors from the single SQL
// authorities under packages/storage/sql/workspace-v4*.sql. Unlike the v3
// generator (scripts/generate-workspace-v3-sql.mjs), the Rust side needs the
// literal schema text -- not just a digest -- because the Rust cold/
// incremental pipeline is the one that will create these files (see plan
// §9: "Rust comprueba lo mismo"). Run via `pnpm generate:workspace-sql`,
// which runs this after the v3 generator.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const authorities = [
  { key: "WORKSPACE_V4_SCHEMA", sqlPath: resolve(root, "packages/storage/sql/workspace-v4.sql") },
  { key: "WORKSPACE_V4_LEXICAL_SCHEMA", sqlPath: resolve(root, "packages/storage/sql/workspace-v4-lexical.sql") },
  { key: "WORKSPACE_V4_SEMANTIC_SCHEMA", sqlPath: resolve(root, "packages/storage/sql/workspace-v4-semantic.sql") },
].map((entry) => ({ ...entry, sql: readFileSync(entry.sqlPath, "utf8") }));

const generatedTsPath = resolve(root, "packages/storage/src/workspace-v4-sql.generated.ts");
const generatedRustPath = resolve(root, "crates/urdira-indexing-core/src/workspace_v4_sql.rs");

writeFileSync(
  generatedTsPath,
  `/* c8 ignore file */\n// Generated by scripts/generate-workspace-v4-sql.mjs; edit packages/storage/sql/workspace-v4*.sql.\n${authorities.map(({ key, sql }) => `export const ${key} = ${JSON.stringify(sql)};`).join("\n")}\n`,
  "utf8",
);

writeFileSync(
  generatedRustPath,
  `// Generated by scripts/generate-workspace-v4-sql.mjs; edit packages/storage/sql/workspace-v4*.sql.\n${authorities.map(({ key, sql }) => `pub const ${key}: &str =\n    ${JSON.stringify(sql)};`).join("\n")}\n`,
  "utf8",
);

// Keep generated Rust stable under the repository's formatter so
// regeneration is a clean, reviewable operation. Scoped to this one crate
// (unlike the v3 generator's `cargo fmt --all`) and best-effort: a sibling
// in-progress crate elsewhere in the workspace with an incomplete manifest
// (no src/lib.rs yet) makes `cargo metadata` -- and therefore any `--all`
// or workspace-wide cargo invocation -- fail for reasons unrelated to this
// file, and that must not block regenerating the SQL mirrors here.
try {
  execFileSync("cargo", ["fmt", "-p", "urdira-indexing-core"], { cwd: root, stdio: "ignore" });
} catch (error) {
  console.warn(`workspace-v4 SQL: skipped cargo fmt (${error instanceof Error ? error.message : String(error)})`);
}

console.log(`workspace-v4 SQL generated (${authorities.map(({ key, sql }) => `${key}=sha256:${createHash("sha256").update(sql, "utf8").digest("hex").slice(0, 12)}…`).join(", ")})`);

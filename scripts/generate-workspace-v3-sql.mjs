#!/usr/bin/env node
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const authorityPath = resolve(root, "packages/storage/sql/workspace-v3.sql");
const schemaPath = resolve(root, "packages/storage/src/schema.ts");
const generatedTsPath = resolve(root, "packages/storage/src/workspace-v3-sql.generated.ts");
const generatedRustPath = resolve(root, "crates/urdira-indexing-core/src/workspace_v3_sql.rs");
const publicationAuthorityPath = resolve(root, "packages/storage/sql/publication-v3.sql");
const publicationGeneratedTsPath = resolve(root, "packages/storage/src/publication-v3-sql.generated.ts");
const publicationGeneratedRustPath = resolve(root, "crates/urdira-indexing-worker/src/publication_v3_sql.rs");

mkdirSync(dirname(authorityPath), { recursive: true });

// The first invocation extracts the already-approved schema verbatim. Later
// invocations have one SQL authority and never read the TypeScript wrapper.
if (!existsSync(authorityPath)) {
  const schema = readFileSync(schemaPath, "utf8");
  const startMarker = "export const WORKSPACE_SCHEMA = `";
  const start = schema.indexOf(startMarker);
  if (start < 0) throw new Error(`Cannot find ${startMarker} in ${schemaPath}`);
  const bodyStart = start + startMarker.length;
  const bodyEnd = schema.indexOf("`;", bodyStart);
  if (bodyEnd < 0) throw new Error(`Cannot find end of WORKSPACE_SCHEMA in ${schemaPath}`);
  writeFileSync(authorityPath, schema.slice(bodyStart, bodyEnd), "utf8");
}

const sql = readFileSync(authorityPath, "utf8");
const digest = `sha256:${createHash("sha256").update(sql, "utf8").digest("hex")}`;
const publicationSql = readFileSync(publicationAuthorityPath, "utf8");
const publicationDigest = `sha256:${createHash("sha256").update(publicationSql, "utf8").digest("hex")}`;
const publicationEntries = publicationSql.split(/^-- name: /mu).slice(1).map((block) => {
  const newline = block.indexOf("\n");
  const name = block.slice(0, newline).trim();
  const statement = block.slice(newline + 1).trim();
  const key = name.replace(/_([a-z])/gu, (_match, letter) => letter.toUpperCase());
  return { key, name: name.toUpperCase(), statement };
});
if (publicationEntries.length === 0) throw new Error(`No publication SQL statements found in ${publicationAuthorityPath}`);

writeFileSync(
  generatedTsPath,
  `/* c8 ignore file */\n// Generated by scripts/generate-workspace-v3-sql.mjs; edit packages/storage/sql/workspace-v3.sql.\nexport const WORKSPACE_SCHEMA = ${JSON.stringify(sql)};\nexport const WORKSPACE_V3_SCHEMA_DIGEST = ${JSON.stringify(digest)};\n`,
  "utf8",
);

writeFileSync(
  generatedRustPath,
  `// Generated by scripts/generate-workspace-v3-sql.mjs; edit packages/storage/sql/workspace-v3.sql.\npub const WORKSPACE_V3_SCHEMA_DIGEST: &str =\n    ${JSON.stringify(digest)};\n`,
  "utf8",
);

const schema = readFileSync(schemaPath, "utf8");
const startMarker = "export const WORKSPACE_SCHEMA = `";
const start = schema.indexOf(startMarker);
if (start >= 0) {
  const bodyStart = start + startMarker.length;
  const bodyEnd = schema.indexOf("`;", bodyStart);
  if (bodyEnd < 0) throw new Error(`Cannot find end of WORKSPACE_SCHEMA in ${schemaPath}`);
  const replacement = `import { WORKSPACE_SCHEMA } from "./workspace-v3-sql.generated.js";\nexport { WORKSPACE_SCHEMA };`;
  writeFileSync(schemaPath, `${schema.slice(0, start)}${replacement}${schema.slice(bodyEnd + 2)}`, "utf8");
}

const rustPath = resolve(root, "crates/urdira-indexing-core/src/lib.rs");
let rust = readFileSync(rustPath, "utf8");
const digestBlock = /\/\/\/ Digest of `packages\/storage\/src\/schema\.ts`'s v3 workspace authority\.[\s\S]*?pub const WORKSPACE_V3_SCHEMA_DIGEST: &str =\s*"[^"]+";\n/;
rust = rust.replace(digestBlock, "mod workspace_v3_sql;\npub use workspace_v3_sql::WORKSPACE_V3_SCHEMA_DIGEST;\n");
writeFileSync(rustPath, rust, "utf8");

writeFileSync(
  publicationGeneratedTsPath,
  `/* c8 ignore file */\n// Generated by scripts/generate-workspace-v3-sql.mjs; edit packages/storage/sql/publication-v3.sql.\nexport const PUBLICATION_SQL = ${JSON.stringify(Object.fromEntries(publicationEntries.map(({ key, statement }) => [key, statement])), null, 2)} as const;\nexport const PUBLICATION_V3_SQL_DIGEST = ${JSON.stringify(publicationDigest)};\n`,
  "utf8",
);
writeFileSync(
  publicationGeneratedRustPath,
  `// Generated by scripts/generate-workspace-v3-sql.mjs; edit packages/storage/sql/publication-v3.sql.\n${publicationEntries.map(({ name, statement }) => `pub const ${name}: &str =\n    ${JSON.stringify(statement)};`).join("\n")}\npub const PUBLICATION_V3_SQL_DIGEST: &str =\n    ${JSON.stringify(publicationDigest)};\n`,
  "utf8",
);

// Keep generated Rust stable under the repository's formatter so regeneration
// is a clean, reviewable operation. Best-effort: a sibling in-progress crate
// elsewhere in the workspace with an incomplete manifest (no src/lib.rs yet)
// makes `cargo metadata` -- and therefore this workspace-wide `cargo fmt
// --all` -- fail for reasons unrelated to this generator, and that must not
// block regenerating the SQL mirrors here.
try {
  execFileSync("cargo", ["fmt", "--all"], { cwd: root, stdio: "ignore" });
} catch (error) {
  console.warn(`workspace-v3 SQL: skipped cargo fmt (${error instanceof Error ? error.message : String(error)})`);
}

console.log(`workspace-v3 SQL generated (${digest})`);
